#!/usr/bin/env python
"""split.py - cut the two oversized sources into Merlin 8 PUT segments.

Merlin 8 will not load a source file over roughly 24K; TEST038.S.txt is
53K and FORTH.GFX.S.txt is 30K, so neither can be assembled on the Apple
as one file.  This writes a short root file of PUT directives plus one
file per section into merlin8/.

The single-file sources stay canonical.  merlin8/ is a BUILD PRODUCT:
regenerate it with this script rather than editing it, or the two copies
will drift.  tools/mkall.sh --merlin8 assembles the split version and
checks the objects come out byte-identical to the monolithic build.

Usage:  python tools/split.py
"""
import io, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT  = os.path.join(ROOT, "merlin8")

# (segment name, first line, what it holds) - first line is 1-based and
# inclusive; each segment runs to the line before the next one starts.
KERNEL = [
    ("FEQU",   7, "ROM and ProDOS equates, the memory map, zero page,"
                  " the boot copy at $2000 and the cold start at $0800"),
    ("FMODLD", 233, "MODLD - the relocating module loader"),
    ("FMATH",  981, "32-bit arithmetic, file support, MLI parameter blocks"),
    ("FCORE",  1471, "DOVAR, DODOES and DODO, then the primitive words"
                     " the compiler threads together"),
    ("FCOMP",  2272, "the compiler: the immediate words, : and ;"),
    ("FDISK",  2605, "LOAD, GREN, BLOAD, SREN - disk and module words"),
    ("FEXTRA", 3005, "SEED and RND, CREATE and DOES>, strings,"
                     " DIR and RUN, and the end-of-kernel equates"),
]
GFX = [
    ("GEQU",   17, "the kernel jump table, module communication block,"
                   " ROM and soft switches, line tables, zero page,"
                   " the fixup count, and the ten byte module header"),
    ("GHIRES", 114, "the hi-res engine: GFINIT, HDIV7, HADDR, HONSCR,"
                    " HDOT, the draw/xor plotters, HCLR and SHDRAW"),
    ("GDICT",  439, "the dictionary: HGR through BTN - hi-res words,"
                    " shapes, paddles and buttons"),
    ("GLORES", 891, "the lo-res screen, MIXED and SHOW"),
    ("GFIXUP", 1202, "the relocation fixup list"),
]

JOBS = [
    ("TEST038.S.txt",   "FORTH.S", KERNEL, 6,
     "FORTH.SYSTEM - the kernel, in Merlin 8 PUT segments"),
    ("FORTH.GFX.S.txt", "GFX.S",   GFX,    16,
     "FORTH.GFX - the graphics module, in Merlin 8 PUT segments"),
]


def read(path):
    return io.open(path, encoding="ascii", newline="").read().split("\n")


def write(path, lines):
    # The final newline matters: without it an assembler can drop the last
    # line.  (NREL used to be that line; it now sits in the first segment,
    # where the module header can see it on pass 1.)
    text = "\n".join(lines)
    if not text.endswith("\n"):
        text += "\n"
    io.open(path, "w", encoding="ascii", newline="\n").write(text)


def banner(name, what, src):
    """A short header for a segment file, wrapped under 50 columns."""
    out = ["*" + "=" * 45,
           "* %s.S - PUT segment of %s" % (name, src),
           "*"]
    line = "*"
    for word in what.split():
        if len(line) + 1 + len(word) > 48:
            out.append(line)
            line = "*"
        line += " " + word
    out.append(line)
    out.append("* Generated by tools/split.py - do not edit here,")
    out.append("* edit %s and run the script again." % src)
    out.append("*" + "=" * 45)
    return out


def main():
    if not os.path.isdir(OUT):
        os.makedirs(OUT)
    total_problems = 0
    for src, rootname, segs, hdr, title in JOBS:
        lines = read(os.path.join(ROOT, src))
        n = len(lines)
        while n and lines[n - 1] == "":          # ignore a trailing newline
            n -= 1
        bounds = [s[1] for s in segs] + [n + 1]

        root = lines[:hdr]                       # header comment + the xc line
        root.append("* Merlin 8 cannot load a source file over about")
        root.append("* 24K, so the body is split.  The PUT list below")
        root.append("* is also the order it assembles in.")
        root.append("*")
        for i, (name, _, what) in enumerate(segs):
            size = sum(len(lines[j - 1]) + 1
                       for j in range(bounds[i], bounds[i + 1]))
            root.append(" put %-8s           ; %5d bytes" % (name, size))
            body = banner(name, what, src) + lines[bounds[i] - 1:bounds[i + 1] - 1]
            write(os.path.join(OUT, name + ".S"), body)
            if size > 22000:
                print("  !! %s.S is %d bytes - over the safe limit" % (name, size))
                total_problems += 1
        write(os.path.join(OUT, rootname), root)
        print("%-18s -> %s + %d segments" % (src, rootname, len(segs)))
        for name, _, _ in segs:
            p = os.path.join(OUT, name + ".S")
            print("      %-10s %6d bytes" % (name + ".S", os.path.getsize(p)))
    return total_problems


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
